// Helper para obter datas relativas (hoje, amanhã, etc)
export function getRelativeDateString(offsetDays: number = 0): string {
  const d = new Date()
  d.setDate(d.getDate() + offsetDays)
  return d.toISOString().split('T')[0]
}

